import Foundation

/// 根据单个 SOCKS5 节点生成 Clash YAML 配置。
///
/// 配置包含节点、“代理选择”策略组和匹配全部流量的规则。
/// 本类型只生成配置文本，不启动代理服务，也不检查服务端的 UDP 支持情况。
struct ClashConfiguration: Sendable {
    // MARK: - 配置输入

    /// 要写入配置的代理节点。
    var node: ProxyNode
    /// 是否在节点配置中启用 UDP。默认值为 `false`。
    var udpEnabled = false

    // MARK: - YAML 编码

    /// 将字符串编码为可直接嵌入 YAML 的双引号标量。
    ///
    /// JSON 字符串字面量可用于此处的 YAML 标量，可统一处理引号、反斜杠和换行。
    /// 此处只编码原生 `String`，不涉及可能自行抛出错误的自定义编码实现。
    ///
    /// - Parameter value: 需要转义的原始字符串。
    /// - Returns: 包含双引号及必要转义字符的字符串字面量。
    private func quote(_ value: String) -> String {
        let data = try! JSONEncoder().encode(value)
        return String(decoding: data, as: UTF8.self)
    }

    /// 可保存为 `.yaml` 文件的完整配置文本，以换行符结尾。
    ///
    /// 监听端口为 7890，禁止局域网访问，并使用规则模式。
    /// 当节点名称与内置出站名称或策略组重名时，为导出名称追加“ · SOCKS5”。
    /// 此处理不修改 `node` 的显示名称。
    ///
    /// - Important: 节点包含认证信息时，生成的文本会以明文保存用户名和密码。
    var yaml: String {
        // 导出名称必须避开 Clash 保留名称以及当前策略组名称。
        let reserved = ["DIRECT", "REJECT", "REJECT-DROP", "PASS", "COMPATIBLE", "GLOBAL", "代理选择"]
        let name = reserved.contains(node.name) ? "\(node.name) · SOCKS5" : node.name
        var lines = [
            "# Generated by Proxy Studio. Contains private credentials.",
            "mixed-port: 7890", "allow-lan: false", "mode: rule", "log-level: info", "",
            "proxies:", "  - name: \(quote(name))", "    type: socks5",
            "    server: \(quote(node.host.trimmingCharacters(in: CharacterSet(charactersIn: "[]"))))",
            "    port: \(node.port)"
        ]
        if let username = node.username, let password = node.password {
            lines += ["    username: \(quote(username))", "    password: \(quote(password))"]
        }
        lines += [
            "    udp: \(udpEnabled ? "true" : "false")", "", "proxy-groups:",
            "  - name: \"代理选择\"", "    type: select", "    proxies:",
            "      - \(quote(name))", "      - DIRECT", "", "rules:", "  - MATCH,代理选择", ""
        ]
        return lines.joined(separator: "\n")
    }
}
